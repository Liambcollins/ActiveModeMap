"""Benchmark: error-vs-N curves for all acquisition strategies across scenarios.

Scenarios:
  well_specified : data generated by the same EB model used for inference
  high_noise     : 4x the nominal detector noise floor
  mismatched     : data generated by a geometry-perturbed EB model (unknown tip
                   set-back, height, tilt, overhang width, tip mass) -- proxy for
                   the real-probe/beam-model discrepancy shown in the manuscript.

Usage: python run_benchmark.py [n_truths] [n_total]
Writes results to benchmark_results.npz
"""

import sys
import time
import numpy as np

from activemodemap import EBForwardModel, VirtualAFM, run_loop
from activemodemap.forward_model import ProbeGeometry

N_TRUTHS = int(sys.argv[1]) if len(sys.argv) > 1 else 6
N_TOTAL = int(sys.argv[2]) if len(sys.argv) > 2 else 10
STRATEGIES = ["eig", "spot", "variance", "random", "equispaced", "gp"]
SCENARIOS = ["well_specified", "high_noise", "mismatched"]

GT_LO = np.array([2.6, 2.3, 1.0, -0.5, -0.2])
GT_HI = np.array([4.2, 3.2, 1.7, 0.5, 0.2])


def sample_ground_truth(model, rng):
    """Draw theta_true with an interior D-NS (resample compliant contacts)."""
    for _ in range(50):
        th = rng.uniform(GT_LO, GT_HI)
        dns, desbs = model.spots_um_from_end(th)
        if 1.0 < dns < 25.0 and 0.5 < desbs < 30.0:
            return th
    return th


def perturbed_geometry(rng):
    g = ProbeGeometry()
    g.tip_setback_um = g.tip_setback_um + rng.uniform(-3, 3)
    g.tip_height_um = g.tip_height_um + rng.uniform(-2, 2)
    g.tilt_deg = g.tilt_deg + rng.uniform(-2, 2)
    g.overhang_width_factor = np.clip(
        g.overhang_width_factor + rng.uniform(-0.15, 0.15), 0.1, 0.9)
    g.tip_mass_ratio = g.tip_mass_ratio * rng.uniform(0.5, 1.6)
    return g


def main():
    model = EBForwardModel()            # inference model (nominal geometry)
    results = {}                        # (scenario, strategy) -> arrays
    t_start = time.time()
    for scen in SCENARIOS:
        for t in range(N_TRUTHS):
            rng = np.random.default_rng(1000 * SCENARIOS.index(scen) + t)
            theta_true = sample_ground_truth(model, rng)
            kwargs = {}
            if scen == "high_noise":
                kwargs["noise_floor"] = 0.32
            if scen == "mismatched":
                gen = EBForwardModel(geom=perturbed_geometry(rng))
                kwargs["mismatch_model"] = gen
            for strat in STRATEGIES:
                rng_run = np.random.default_rng(rng.integers(1 << 31))
                afm = VirtualAFM(model, theta_true, rng=rng_run, **kwargs)
                try:
                    h = run_loop(afm, strat, n_total=N_TOTAL, rng=rng_run)
                    rec = np.array([h["rmse"], h["dns_err"], h["desbs_err"],
                                    h["dns_ci"], h["desbs_ci"]])
                except Exception as exc:  # keep the benchmark alive
                    print(f"FAILED {scen}/{strat}/gt{t}: {exc}", flush=True)
                    rec = np.full((5, N_TOTAL), np.nan)
                results.setdefault((scen, strat), []).append(rec)
                print(f"[{time.time()-t_start:7.1f}s] {scen:15s} gt{t} "
                      f"{strat:11s} final: rmse={rec[0,-1]:.4f} "
                      f"dns={rec[1,-1]:.3f} desbs={rec[2,-1]:.3f}", flush=True)
    out = {f"{s}|{st}": np.array(v) for (s, st), v in results.items()}
    np.savez("benchmark_results.npz", **out,
             strategies=STRATEGIES, scenarios=SCENARIOS)
    print(f"done in {time.time()-t_start:.0f}s -> benchmark_results.npz")


if __name__ == "__main__":
    main()
